// Package watchdog diagnoses stalls in the TWO existing scientific lanes.
// It is observation-only: decisions never issue execution, repairs or authority.
package watchdog

import (
 "errors"
 "fmt"
)
const MaxOrchestrationSeconds uint64=300
var ErrUnsafe=errors.New("FORGE_WATCHDOG_UNAUTHENTICATED_OBSERVATION")
type Phase string
const(
 Orchestration Phase="ORCHESTRATION"
 ScientificExecution Phase="SCIENTIFIC_EXECUTION"
 Quarantined Phase="QUARANTINED"
)
type Observation struct{
 Lane string
 OriginalExperimentID string
 JournalHeadSHA256 string
 OwnerEpoch uint64
 Authenticated bool
 Phase Phase
 LastProgressUnix uint64
 LastWorkerHeartbeatUnix uint64
 WorkerHeartbeatAuthenticated bool
 FirstUseRisk bool
}
type Action string
const(
 Healthy Action="HEALTHY"
 DiagnoseOrchestration Action="DIAGNOSE_RECOVERABLE_STALL"
 DiagnoseWorker Action="RECONCILE_WORKER_WITHOUT_REPLAY"
 ReconcileOriginal Action="RECONCILE_ORIGINAL_NO_REPLAY"
 Isolate Action="INTEGRITY_OR_AUTHORITY_BLOCKED"
)
type Result struct{
 Lane string
 Action Action
 ElapsedSeconds uint64
 WorkerHeartbeatAge uint64
}
func validHash(s string)bool{
 if len(s)!=64{return false}
 for _,c:=range s{if !(c>='0'&&c<='9'||c>='a'&&c<='f'){return false}}
 return true
}
func Assess(now uint64, o Observation)(Result,error){
 r:=Result{Lane:o.Lane,Action:Isolate}
 if (o.Lane!="Wingless"&&o.Lane!="Yggdrasil")||o.OriginalExperimentID==""||
 !o.Authenticated||!validHash(o.JournalHeadSHA256)||o.OwnerEpoch==0||
 o.LastProgressUnix==0||now<o.LastProgressUnix||
 (o.Phase!=Orchestration&&o.Phase!=ScientificExecution&&o.Phase!=Quarantined){
  return r,ErrUnsafe
 }
 r.ElapsedSeconds=now-o.LastProgressUnix
 if o.WorkerHeartbeatAuthenticated{
  if o.LastWorkerHeartbeatUnix==0||now<o.LastWorkerHeartbeatUnix{return r,ErrUnsafe}
  r.WorkerHeartbeatAge=now-o.LastWorkerHeartbeatUnix
 }
 if o.Phase==Quarantined||o.FirstUseRisk{
  r.Action=ReconcileOriginal;return r,nil
 }
 if o.Phase==ScientificExecution{
  // Scientific runtime is deliberately NOT limited to five minutes.
  // A missing/aged independently authenticated heartbeat can prompt
  // reconciliation, never original dispatch or worker relaunch.
  if !o.WorkerHeartbeatAuthenticated||r.WorkerHeartbeatAge>MaxOrchestrationSeconds {
   r.Action=DiagnoseWorker
  }else{r.Action=Healthy}
  return r,nil
 }
 if r.ElapsedSeconds>MaxOrchestrationSeconds{r.Action=DiagnoseOrchestration}else{r.Action=Healthy}
 return r,nil
}
// AssessBoth enforces observation of the original two lanes: there is no
// default lane, autogenerated queue, or substitute scientific program.
func AssessBoth(now uint64, observations []Observation)([2]Result,error){
 var out [2]Result
 if len(observations)!=2{return out,ErrUnsafe}
 seen:=map[string]bool{}
 for _,o:=range observations{
  if seen[o.Lane]{return [2]Result{},ErrUnsafe}
  seen[o.Lane]=true
  r,err:=Assess(now,o);if err!=nil{return [2]Result{},fmt.Errorf("%w: %v",ErrUnsafe,err)}
  if o.Lane=="Wingless"{out[0]=r}else if o.Lane=="Yggdrasil"{out[1]=r}
 }
 if !seen["Wingless"]||!seen["Yggdrasil"]{return [2]Result{},ErrUnsafe}
 return out,nil
}
