#!/usr/bin/env python3
"""L10-B deterministic invented DEVELOPMENT sources and information custody.

No protected L10 family can be generated by this module. All identifiers
are bound to frozen synthetic-only role and seed. Models see *observed*
opaque relation codes plus an explicitly allowed lexicon, never true Claims.
This distinguishes a sufficient-information evaluation from a deliberately
unidentifiable relation mapping.
"""
from __future__ import annotations
from dataclasses import dataclass
from hashlib import sha256
import hmac
import json
import re

from l10_semantic_dev_oracle import Claim, DevelopmentCase, constructed_case, case_identity

SCHEMA="forge.optimizer.language.l10.source-exposure-dev-v1"
DEV_ROLE="L10_SYNTHETIC_DEV"
PROSPECTIVE_ROLE="L10_PROSPECTIVE_NEW_SOURCE_FAMILY"
DEV_SEED=b"L10-B-invented-development-fixtures-only-20261024-v1"
FAMILIES=("dev-bindings","dev-compositions","dev-polarity")
PREDICATE_LEXICON=(("P0","located_in"),("P1","owns"),("P2","parent_of"))
PREDICATE_CODES=tuple(k for k,_ in PREDICATE_LEXICON)
ENTITIES=("Aster","Boreal","Cora","Dana","Eli","Faye","Galen","Hera","Iris","Juno","Kepler","Luna","Mica","Nero","Opal","Pavo")
DEV_SPLITS=("DEV_FIT","DEV_CHECK")
EXPOSURES=("KNOWN_MAPPING","WITHHELD_MAPPING")
FIXTURES_PER_SPLIT=4

@dataclass(frozen=True)
class Observed:
    subject: str
    relation_code: str
    object: str
    polarity: int

@dataclass(frozen=True)
class ModelInput:
    observed: tuple[Observed,...]
    public_lexicon: tuple[tuple[str,str],...]
    information_regime: str

@dataclass(frozen=True)
class Fixture:
    family: str
    split: str
    role: str
    input: ModelInput
    target: DevelopmentCase
    fixture_sha256: str

def require(ok,reason):
    if not ok: raise ValueError("L10_SOURCE_CUSTODY_BLOCKED:"+reason)

def canonical_bytes(value):
    return (json.dumps(value,sort_keys=True,separators=(",",":"),ensure_ascii=False)+"\n").encode()

def _digest(*parts):
    require(all(type(p) in (str,int) for p in parts),"invalid seed derivation")
    return hmac.new(DEV_SEED,"|".join(map(str,parts)).encode(),sha256).digest()

def _int(limit,*parts):
    require(type(limit) is int and limit>0,"invalid limit")
    return int.from_bytes(_digest(*parts)[:8],"big")%limit

def _claims(family,split,index):
    require(family in FAMILIES and split in DEV_SPLITS and type(index) is int
            and 0<=index<FIXTURES_PER_SPLIT,"dev-only source grid")
    count={"dev-bindings":1,"dev-compositions":3,"dev-polarity":2}[family]
    claims=[]
    used=set()
    for pos in range(count):
        # Domain-separate every generated entity by family/split/example
        # while retaining the frozen controlled-English oracle token syntax.
        suffix="F"+str(FAMILIES.index(family))+"S"+str(DEV_SPLITS.index(split))+"I"+str(index)+"T"+str(pos)
        s=ENTITIES[_int(len(ENTITIES),family,split,index,pos,"s")]+suffix
        obj=ENTITIES[_int(len(ENTITIES),family,split,index,pos,"o")]+suffix
        if s==obj:obj=ENTITIES[(_int(len(ENTITIES),family,split,index,pos,"o")+1)%len(ENTITIES)]+suffix
        pred=PREDICATE_LEXICON[_int(3,family,split,index,pos,"predicate")][1]
        pol=(-1 if family=="dev-polarity" and _int(2,family,split,index,pos,"polarity") else 1)
        c=Claim(s,pred,obj,pol)
        require(c not in used,"dev generator duplicate proposition")
        used.add(c)
        claims.append(c)
    return tuple(claims)

def _identity(family,split,regime,case,observed,public):
    body=dict(schema=SCHEMA,role=DEV_ROLE,family=family,split=split,
              regime=regime,case_identity=case.source_identity_sha256,
              observed=[(o.subject,o.relation_code,o.object,o.polarity) for o in observed],
              public_lexicon=public)
    return sha256(canonical_bytes(body)).hexdigest()

def make_dev_fixture(family,split,index,regime):
    # Enforce access control before touching seed or generating any examples.
    require(family in FAMILIES and split in DEV_SPLITS
            and type(index) is int and 0<=index<FIXTURES_PER_SPLIT
            and regime in EXPOSURES,"unqualified/heldout generator request")
    claims=_claims(family,split,index)
    case=constructed_case(family,claims)
    mapping={v:k for k,v in PREDICATE_LEXICON}
    observed=tuple(Observed(c.subject,mapping[c.predicate],c.object,c.polarity) for c in claims)
    lexicon=PREDICATE_LEXICON if regime=="KNOWN_MAPPING" else ()
    mi=ModelInput(observed,lexicon,regime)
    digest=_identity(family,split,regime,case,observed,lexicon)
    result=Fixture(family,split,DEV_ROLE,mi,case,digest)
    validate_fixture(result)
    return result

def validate_fixture(f):
    require(type(f) is Fixture and f.role==DEV_ROLE,"non-development role")
    require(f.family in FAMILIES and f.split in DEV_SPLITS
            and f.input.information_regime in EXPOSURES,"invalid source registration")
    require(type(f.fixture_sha256) is str and re.fullmatch(r"[0-9a-f]{64}",f.fixture_sha256),
            "fixture SHA missing")
    case_identity(f.target)
    claims=f.target.claims
    require(f.target.family_id==f.family,"family drift")
    require(len(f.input.observed)==len(claims),"observation count")
    mapping={v:k for k,v in PREDICATE_LEXICON}
    for actual,truth in zip(f.input.observed,claims):
        require(type(actual) is Observed,"observation structure")
        require((actual.subject,actual.relation_code,actual.object,actual.polarity)==
                (truth.subject,mapping[truth.predicate],truth.object,truth.polarity),
                "observation/target source binding drift")
    must_lex=PREDICATE_LEXICON if f.input.information_regime=="KNOWN_MAPPING" else ()
    require(f.input.public_lexicon==must_lex,"uncontrolled semantic information exposure")
    require(f.fixture_sha256==_identity(f.family,f.split,f.input.information_regime,
                                      f.target,f.input.observed,f.input.public_lexicon),
            "content-addressed fixture identity drift")
    return True

def development_collection(regime="KNOWN_MAPPING"):
    require(regime in EXPOSURES,"prospective mode forbidden")
    fixtures=[make_dev_fixture(f,split,i,regime) for f in FAMILIES
              for split in DEV_SPLITS for i in range(FIXTURES_PER_SPLIT)]
    validate_collection(fixtures,regime)
    return fixtures

def validate_collection(fixtures,regime):
    require(type(fixtures) in (list,tuple) and regime in EXPOSURES,
            "unregistered source regime")
    grid={(x.family,x.split) for x in fixtures}
    require(grid=={(f,s) for f in FAMILIES for s in DEV_SPLITS},
            "missing development family/split")
    require(len(fixtures)==len(FAMILIES)*len(DEV_SPLITS)*FIXTURES_PER_SPLIT,
            "unexpected development dataset size")
    seen_ids=set()
    seen_case_ids=set()
    for f in fixtures:
        validate_fixture(f)
        require(f.input.information_regime==regime,"mixed information regimes")
        require(f.fixture_sha256 not in seen_ids and f.target.source_identity_sha256 not in seen_case_ids,
                "duplicate/overlapping development source")
        seen_ids.add(f.fixture_sha256)
        seen_case_ids.add(f.target.source_identity_sha256)
    return True

def manifest_only(fixtures,regime):
    validate_collection(fixtures,regime)
    rows=[]
    for f in fixtures:
        rows.append({"family_sha256":sha256(f.family.encode()).hexdigest(),
                     "split":f.split,"information_regime":regime,
                     "fixture_sha256":f.fixture_sha256,
                     "claim_count":len(f.target.claims)})
    # No raw entity names, proposition text, paraphrases or heldout data.
    return dict(schema="forge.optimizer.language.l10.dev-source-identity-manifest-v1",
                status="DEVELOPMENT_ONLY_NEW_PROSPECTIVE_SOURCE_UNGENERATED",
                role=DEV_ROLE,source_namespace_sha256=sha256(DEV_SEED).hexdigest(),
                method_semantic_mapping=regime,fixtures=len(fixtures),
                families=len(FAMILIES),rows=rows,
                protected_source_seed_available=False,
                prospective_examples_generated=0,
                official_webnlg_test_consumed=False,
                l9_audit_reused=False,scientific_go=False)

def public_input(f):
    validate_fixture(f)
    return f.input
