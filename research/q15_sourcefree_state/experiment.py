"""Q15 synthetic NCI-04 predictive state TRAIN + validation; no original science.

All labels are generated by this standalone synthetic program. It does not
import, access or reset MiniGrid, Pycolab, CKB, original scientific cohorts or
external APIs. The frozen F_C/F_D unfamiliar cohorts are never instantiated.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import random
import time
import tracemalloc
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROTOCOL_BLOB = "3dfe97f158bcb8939d1d40d0a95c3cf3b0f9bb05"
FROZEN_PATH = HERE / "FROZEN_PROTOCOL.json"
MASK64 = (1 << 64) - 1
FAMILY_NAMES = ("F_A", "F_B")
NAMES = ("LINEAR_PREDICTIVE_STATE", "TANH_RNN",
         "TRAINED_BAYES_FILTER", "TRAINED_SYMBOLIC_MAJORITY",
         "TRAINED_CURRENT_ONLY_LOGISTIC")


def need(ok: bool, message: str) -> None:
    if not ok:
        raise RuntimeError("Q15_" + message)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def seed_for(role: str, family: str, index: int) -> int:
    return int.from_bytes(hashlib.sha256(
        ("q15-v1:" + role + ":" + family + ":" + str(index))
        .encode("utf-8")).digest()[:8], "big")


def init_seed(name: str, restart: int) -> int:
    return int.from_bytes(hashlib.sha256(
        ("q15-init:" + name + ":" + str(restart))
        .encode("utf-8")).digest()[:8], "big")


def load_frozen() -> dict:
    raw = FROZEN_PATH.read_bytes()
    git_blob = hashlib.sha1(
        b"blob " + str(len(raw)).encode("ascii") + b"\0" + raw
    ).hexdigest()
    need(git_blob == PROTOCOL_BLOB, "FROZEN_PROTOCOL_BLOB_DRIFT")
    doc = json.loads(raw)
    need(doc["schema"] == "forge.nci04.q15.source-free-state-train-development.v1",
         "PROTOCOL_SCHEMA_DRIFT")
    gen = doc["generator"]
    need(gen["only_allowed_cohorts_in_Q15"] == ["train", "validation"],
         "ROLE_SCOPE_DRIFT")
    need([x["name"] for x in gen["training_families"]] == list(FAMILY_NAMES)
         and [x["name"] for x in gen["validation_families"]] == list(FAMILY_NAMES),
         "TRAIN_DEV_FAMILY_DRIFT")
    need(doc["optimizer"]["recurrent_epochs"] == 80
         and doc["optimizer"]["restarts"] == [0, 1, 2],
         "FROZEN_TRAINING_DRIFT")
    return doc


def generate(role: str, family: dict) -> list:
    # Fail closed before even creating RNG state for unfamiliar families.
    need(role in ("train", "validation") and family["name"] in FAMILY_NAMES,
         "HELD_OR_ORIGINAL_GENERATION_FORBIDDEN")
    need(family["name"] in FAMILY_NAMES and 0 < family["noise"] < 0.5
         and 0 < family["hazard"] < 0.5,
         "FAMILY_PARAM_INVALID")
    episodes = []
    for idx in range(family["episodes"]):
        rng = random.Random(seed_for(role, family["name"], idx))
        label = rng.randrange(2)
        xs, ys = [], []
        for t in range(family["steps"]):
            if t > 0 and rng.random() < family["hazard"]:
                label = 1 - label
            xbit = label if rng.random() >= family["noise"] else 1-label
            xs.append(2*xbit-1)
            ys.append(label)
        episodes.append((family["name"], tuple(xs), tuple(ys)))
    return episodes


def cohort_digest(data: list) -> str:
    raw = json.dumps(data, separators=(",", ":"), ensure_ascii=True).encode()
    return sha256(raw)


def sigmoid(value: float) -> float:
    if value >= 0:
        return 1/(1+math.exp(-value))
    temp = math.exp(value)
    return temp/(1+temp)


def logloss(logit: float, y: int) -> float:
    return max(0.0, logit)+math.log1p(math.exp(-abs(logit)))-y*logit


def recurrent_forward(kind: str, par: list, xs: tuple) -> tuple:
    a = 0.99*math.tanh(par[0])
    w = par[1]
    h_bias = par[2] if kind == "TANH_RNN" else 0.0
    v, bias = (par[3], par[4]) if kind == "TANH_RNN" else (par[2], par[3])
    hs = [0.0]
    logits = []
    for x in xs:
        pre = a*hs[-1]+w*x+h_bias
        h = math.tanh(pre) if kind == "TANH_RNN" else pre
        hs.append(h)
        logits.append(v*h+bias)
    return hs, logits


def recurrent_gradient(kind: str, par: list, xs: tuple, ys: tuple) -> list:
    hs, logits = recurrent_forward(kind, par, xs)
    g = [0.0]*len(par)
    a = 0.99*math.tanh(par[0])
    da_raw = 0.99*(1-math.tanh(par[0])**2)
    readout_idx = 3 if kind == "TANH_RNN" else 2
    back = 0.0
    for t in range(len(xs)-1, -1, -1):
        delta = sigmoid(logits[t])-ys[t]
        g[readout_idx] += delta*hs[t+1]
        g[readout_idx+1] += delta
        dh = delta*par[readout_idx]+back
        local = dh*(1-hs[t+1]**2) if kind == "TANH_RNN" else dh
        g[0] += local*hs[t]*da_raw
        g[1] += local*xs[t]
        if kind == "TANH_RNN":
            g[2] += local
        back = a*local
    return g


def adam_step(params: list, grad: list, mom: list, variance: list,
              step: int, lr: float, clip: float) -> None:
    length = math.sqrt(sum(z*z for z in grad))
    if length > clip:
        grad = [z*clip/length for z in grad]
    for i, d in enumerate(grad):
        mom[i] = 0.9*mom[i]+0.1*d
        variance[i] = 0.999*variance[i]+0.001*d*d
        estimate = mom[i]/(1-0.9**step)
        scale = variance[i]/(1-0.999**step)
        params[i] -= lr*estimate/(math.sqrt(scale)+1e-8)
    need(all(math.isfinite(x) for x in params), "NONFINITE_TRAINED_PARAM")


def nll_episode(kind: str, params: list, episode: tuple, meta=None) -> float:
    _, xs, ys = episode
    if kind in ("LINEAR_PREDICTIVE_STATE", "TANH_RNN"):
        logits = recurrent_forward(kind, params, xs)[1]
    elif kind == "TRAINED_BAYES_FILTER":
        noise, hazard = meta["noise"], meta["hazard"]
        p = 0.5
        logits = []
        for x in xs:
            prior = p*(1-hazard)+(1-p)*hazard
            likelihood1 = 1-noise if x==1 else noise
            likelihood0 = noise if x==1 else 1-noise
            p = prior*likelihood1 / (
                prior*likelihood1 + (1-prior)*likelihood0)
            p = min(1-1e-9, max(1e-9, p))
            logits.append(math.log(p/(1-p)))
    elif kind == "TRAINED_SYMBOLIC_MAJORITY":
        running, logits = 0, []
        for x in xs:
            running += x
            logits.append(params[0]*running+params[1])
    elif kind == "TRAINED_CURRENT_ONLY_LOGISTIC":
        logits = [params[0]*x+params[1] for x in xs]
    else:
        raise RuntimeError("Q15_UNKNOWN_MODEL")
    return sum(logloss(z, y) for z,y in zip(logits, ys))/len(ys)


def eval_models(kind: str, params: list, episodes: list, meta=None) -> dict:
    grouped = {name: [] for name in FAMILY_NAMES}
    for ep in episodes:
        grouped[ep[0]].append(nll_episode(kind, params, ep, meta))
    need(all(grouped.values()), "EMPTY_VALIDATION_FAMILY")
    family_mean = {key: sum(vals)/len(vals)
                   for key, vals in grouped.items()}
    return {"by_family":family_mean,
            "mean":sum(family_mean.values())/len(family_mean)}


def train_recurrent(kind: str, episodes: list, val: list, cfg: dict) -> tuple:
    best = None
    epochs = cfg["recurrent_epochs"]
    batch = cfg["recurrent_minibatch_episodes"]
    peak_max, train_cpu = 0, 0.0
    records = []
    for restart in cfg["restarts"]:
        rng = random.Random(init_seed(kind, restart))
        params = [rng.uniform(0.0,1.0), rng.uniform(0.1,0.5)]
        if kind == "TANH_RNN":
            params += [rng.uniform(-0.05,0.05),
                       rng.uniform(0.4,1.0), 0.0]
        else:
            params += [rng.uniform(0.4,1.0), 0.0]
        avg = [0.0]*len(params)
        var = [0.0]*len(params)
        iteration = 0
        tr = time.process_time()
        tracemalloc.start()
        for epoch in range(epochs):
            indices = list(range(len(episodes)))
            rng.shuffle(indices)
            for start in range(0,len(indices),batch):
                selected = indices[start:start+batch]
                grad = [0.0]*len(params)
                steps = 0
                for idx in selected:
                    _,xs,ys=episodes[idx]
                    g = recurrent_gradient(kind, params, xs,ys)
                    steps += len(ys)
                    for i in range(len(g)):
                        grad[i] += g[i]
                grad = [x/steps for x in grad]
                iteration += 1
                adam_step(params,grad,avg,var,iteration,
                          cfg["adam_lr"],cfg["grad_clip_l2"])
        peak = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
        train_cpu += time.process_time()-tr
        peak_max = max(peak_max,peak)
        score = eval_models(kind,params,val)
        records.append({"restart":restart,"nll":score["mean"]})
        if best is None or score["mean"] < best[0]:
            best=(score["mean"], restart,params[:],score)
    return (best[2],best[3],{"train_cpu_seconds":train_cpu,
                            "peak_python_bytes":peak_max,
                            "validation_restart_scores":records,
                            "selected_restart":best[1],
                            "optimizer_steps_per_restart":epochs*(
                                math.ceil(len(episodes)/batch))})


def feature_seq(kind: str, xs: tuple) -> list:
    if kind == "TRAINED_SYMBOLIC_MAJORITY":
        total=0
        output=[]
        for x in xs:
            total += x
            output.append(total)
        return output
    return xs


def train_logistic(kind: str, episodes: list, cfg: dict) -> tuple:
    params=[0.0,0.0]
    m=[0.0,0.0]
    var=[0.0,0.0]
    it=0
    rng=random.Random(init_seed(kind,0))
    tic=time.process_time()
    tracemalloc.start()
    for _ in range(cfg["scalar_logistic_epochs"]):
        indices=list(range(len(episodes)))
        rng.shuffle(indices)
        for start in range(0,len(indices),cfg["scalar_logistic_minibatch_episodes"]):
            grad=[0.0,0.0]
            steps=0
            for idx in indices[start:start+cfg["scalar_logistic_minibatch_episodes"]]:
                _,xs,ys=episodes[idx]
                for feature,y in zip(feature_seq(kind,xs),ys):
                    d=sigmoid(params[0]*feature+params[1])-y
                    grad[0]+=d*feature
                    grad[1]+=d
                    steps+=1
            it+=1
            adam_step(params,[x/steps for x in grad],m,var,it,
                      cfg["adam_lr"],cfg["grad_clip_l2"])
    peak=tracemalloc.get_traced_memory()[1]
    tracemalloc.stop()
    return params,{"train_cpu_seconds":time.process_time()-tic,
                   "peak_python_bytes":peak,
                   "optimizer_steps":it}


def train_bayes(data:list) -> tuple:
    mismatch, total, flips, transitions=0,0,0,0
    tic=time.process_time()
    for _,xs,ys in data:
        mismatch += sum(((x==1)!=bool(y)) for x,y in zip(xs,ys))
        total +=len(xs)
        flips +=sum(a!=b for a,b in zip(ys,ys[1:]))
        transitions +=len(ys)-1
    p=max(1e-4,min(.4999,mismatch/total))
    h=max(1e-4,min(.4999,flips/transitions))
    return {"noise":p,"hazard":h},{"train_cpu_seconds":time.process_time()-tic,
                                  "peak_python_bytes":0,
                                  "optimizer_steps":1}


def main() -> None:
    parser=argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("selftest","train-dev"),required=True)
    args=parser.parse_args()
    doc=load_frozen()
    if args.mode=="selftest":
        need(seed_for("train","F_A",0)!=seed_for("validation","F_A",0),
             "COHORT_SEED_COLLISION")
        p=[0.5,0.2,0.4,0.0]
        toy=("TOY",(+1,-1,+1),(1,0,1))
        need(len(recurrent_gradient("LINEAR_PREDICTIVE_STATE",p,toy[1],toy[2]))==4,
             "CANDIDATE_GRADIENT_SHAPE")
        need(len(recurrent_gradient("TANH_RNN",[0.5,0.2,0.,0.4,0.],toy[1],toy[2]))==5,
             "TRAINED_RNN_GRADIENT_SHAPE")
        need(math.isfinite(nll_episode("LINEAR_PREDICTIVE_STATE",p,toy)),
             "SELFTEST_NONFINITE")
        try:
            generate("held",{"name":"F_C","noise":.33,"hazard":.22,
                             "steps":24,"episodes":128})
        except RuntimeError as error:
            need("Q15_HELD_OR_ORIGINAL_GENERATION_FORBIDDEN" in str(error),
                 "HELD_FORBID_ASSERTION")
        else:
            raise RuntimeError("Q15_HELD_SYNTHETIC_NOT_BLOCKED")
        print("Q15_SOURCE_FREE_AND_NO_HELD_GENERATION_SELFTEST=PASS")
        return

    train_spec=doc["generator"]["training_families"]
    val_spec=doc["generator"]["validation_families"]
    train=[ep for f in train_spec for ep in generate("train",f)]
    val=[ep for f in val_spec for ep in generate("validation",f)]
    need(len(train)==512 and len(val)==128, "FROZEN_TRAIN_DEV_COUNT_DRIFT")
    cfg=doc["optimizer"]
    results={}
    params={}
    costs={}
    # Exactly identical episodes/labels for all four trained approaches.
    for kind in NAMES:
        if kind in ("LINEAR_PREDICTIVE_STATE","TANH_RNN"):
            p,score,cost=train_recurrent(kind,train,val,cfg)
        elif kind=="TRAINED_BAYES_FILTER":
            p,cost=train_bayes(train)
            score=eval_models(kind,[],val,p)
        else:
            p,cost=train_logistic(kind,train,cfg)
            score=eval_models(kind,p,val)
        tic=time.process_time()
        repeat=eval_models(kind,p if isinstance(p,list) else [],val,
                           p if kind=="TRAINED_BAYES_FILTER" else None)
        cost["validation_inference_cpu_seconds"]=time.process_time()-tic
        need(abs(repeat["mean"]-score["mean"])<=1e-12,
             "VALIDATION_NONDETERMINISTIC")
        params[kind]=p
        costs[kind]=cost
        score["parameters"]=len(p) if isinstance(p,list) else 2
        score["online_state_floats"]=(
            0 if kind=="TRAINED_CURRENT_ONLY_LOGISTIC" else 1)
        score["checkpoint_bytes"]=len(json.dumps(p,sort_keys=True,
                                    separators=(",",":")).encode())
        results[kind]=score
        print("Q15_DEV_MODEL="+kind+
              " NLL="+format(score["mean"],".9f"),flush=True)
    candidate=results["LINEAR_PREDICTIVE_STATE"]
    others=[k for k in NAMES if k!="LINEAR_PREDICTIVE_STATE"]
    best=min(others,key=lambda n:results[n]["mean"])
    gain=results[best]["mean"]-candidate["mean"]
    per_family={n: results[best]["by_family"][n]-
                candidate["by_family"][n] for n in FAMILY_NAMES}
    cpu_candidate=(costs["LINEAR_PREDICTIVE_STATE"]["train_cpu_seconds"]+
                   costs["LINEAR_PREDICTIVE_STATE"]["validation_inference_cpu_seconds"])
    cpu_tanh=(costs["TANH_RNN"]["train_cpu_seconds"]+
              costs["TANH_RNN"]["validation_inference_cpu_seconds"])
    criteria={
      "gain_at_least_0_010_nats":gain>=0.010,
      "positive_both_dev_families":all(x>0 for x in per_family.values()),
      "one_scalar_memory":results["LINEAR_PREDICTIVE_STATE"]["online_state_floats"]==1
          and results["TANH_RNN"]["online_state_floats"]==1,
      "candidate_train_plus_eval_cpu_leq_1_05_tanh":cpu_candidate<=1.05*cpu_tanh
    }
    verdict="DEV_ADVANCE_TO_SEPARATELY_AUTHORIZED_HOLD_ONLY" if all(criteria.values()) \
        else "DEV_NO_GO_STOP_BEFORE_HELD"
    report={
      "schema":"forge.nci04.q15.sourcefree.train-dev-result.v1",
      "preregistered_protocol_blob":PROTOCOL_BLOB,
      "not_original_science":True,
      "train_episodes":len(train),
      "validation_episodes":len(val),
      "unfamiliar_family_F_C_or_F_D_generated":False,
      "original_source_episodes":0,
      "train_digest":cohort_digest(train),
      "validation_digest":cohort_digest(val),
      "scores_nats_per_time_step":results,
      "training_and_prediction_costs":costs,
      "selected_checkpoint_sha256_by_model":{
          n:sha256(json.dumps(p,sort_keys=True,
                  separators=(",",":")).encode()) for n,p in params.items()},
      "best_conventional_control":best,
      "gain_over_best_conventional_nats_per_step":gain,
      "gain_by_dev_family":per_family,
      "frozen_gate":criteria,
      "verdict":verdict,
      "protected_scientific_first_use":False
    }
    print("Q15_RESULT_JSON="+json.dumps(report,sort_keys=True,
          separators=(",",":"),allow_nan=False),flush=True)
    print("Q15_TRAIN_DEV_VERDICT="+verdict,flush=True)
    print("Q15_HELD_FAMILIES=NOT_GENERATED",flush=True)
    print("Q15_ORIGINAL_MINIGRID_PYCOLAB_CKB_SCIENCE=NOT_TOUCHED",flush=True)


if __name__=="__main__":
    main()
