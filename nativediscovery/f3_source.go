func F3Development()(F3Report,error){
 generation,err:=F3Generate();if err!=nil{return F3Report{},err}
 ids:=make([]string,0,len(generation.Candidates))
 for _,c:=range generation.Candidates{ids=append(ids,c.ID)}
 sort.Strings(ids)
 report:=F3Report{
  Schema:F3Schema,AcceptedBase:F3Base,GeneratedSourceSHA256:generation.SourceSHA256,
  NativeGeneratorFrozenSHA256:generation.GeneratorFrozenSHA256,
  SyntheticHistorySHA256:generation.TrainingHistorySHA256,
  Candidates:generation.Candidates,SelectionSeeds:[2]uint32{17,31},
  HeldoutDevelopmentSeeds:[2]uint32{59,83},
  FrozenRequiredGainPP:F3MinAdvantagePP,FrozenMaxRetentionLossPP:F3MaxRetentionLossPP,
  DevelopmentStatus:"DEV_NO_GO",GeneratedCompiledSource:true,
 }
 trainGain:=map[string]float64{}
 for _,id:=range ids{for _,seed:=range report.SelectionSeeds{
  row,err:=f3Trial(id,seed);if err!=nil{return F3Report{},err}
  report.TrainingResults=append(report.TrainingResults,row)
  better:=row.FactorizedChangedPct
  if row.TabularChangedPct>better{better=row.TabularChangedPct}
  if row.ExistingF2NativeChangedPct>better{better=row.ExistingF2NativeChangedPct}
  trainGain[id]+=row.NativeChangedPct-better
 }}
 best:=ids[0]
 for _,id:=range ids[1:]{
  if trainGain[id]>trainGain[best]{best=id}
 }
 report.SelectedCandidateID=best
 successes:=0
 for _,id:=range ids{for _,seed:=range report.HeldoutDevelopmentSeeds{
  row,err:=f3Trial(id,seed);if err!=nil{return F3Report{},err}
  report.HeldoutResults=append(report.HeldoutResults,row)
  if id!=best{continue}
  stronger:=row.FactorizedChangedPct
  if row.TabularChangedPct>stronger{stronger=row.TabularChangedPct}
  if row.ExistingF2NativeChangedPct>stronger{stronger=row.ExistingF2NativeChangedPct}
  if row.NativeChangedPct>=stronger+F3MinAdvantagePP &&
   row.NativeBaseBeforePct-row.NativeBaseAfterPct<=F3MaxRetentionLossPP &&
   row.NativeColdBasePct==row.NativeBaseAfterPct{successes++}
 }}
 report.CriterionMet=successes==len(report.HeldoutDevelopmentSeeds)
 if report.CriterionMet{report.DevelopmentStatus="SYNTHETIC_PROVISIONAL_ONLY"}
 // F3 builds source from three fixed, inspected Go grammar blocks and tests
 // exact source. It does not produce unbounded new algorithms or run FSA.
 return report,nil
}
