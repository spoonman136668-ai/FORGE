// Eureka F14: a portable, source-bound offline development-cycle receipt.
// This deliberately does not introduce a worker, controller, queue or owner action.
package nativediscovery

import (
	"bytes"
	"encoding/json"
	"errors"
	"io"
)

const (
	F14Schema   = "forge.native-discovery.offline-cycle-evidence.dev.v1"
	F14MaxBytes = 4 << 20
	F14NO_GO    = "F14_DEV_NO_GO_NO_OWNER_ADMISSION"
)

var errF14 = errors.New("FORGE_EUREKA_F14_EVIDENCE_OR_AUTHORITY_INVALID")

// F14Evidence binds a real F8 learned-state export to the source-bound F10
// strongest-control scorecard and F13 changed-world result. F10/F13 retain
// their own parent lineage and the earlier negative results. The external
// artifact SHA must be anchored by the caller; a local hash is not custody.
type F14Evidence struct {
	Schema                          string    `json:"schema"`
	F8Artifact                      []byte    `json:"f8_artifact"`
	F8ArtifactSHA256                string    `json:"f8_artifact_sha256"`
	F8CheckpointSHA256              string    `json:"f8_checkpoint_sha256"`
	F10                             F10Review `json:"f10"`
	F13                             F13Report `json:"f13"`
	Classification                  string    `json:"classification"`
	DevelopmentOnly                 bool      `json:"development_only"`
	EarlierNegativeResultsPreserved bool      `json:"earlier_negative_results_preserved"`
	IndependentFirstUseConsumed     bool      `json:"independent_first_use_consumed"`
	ScientificAccepted              bool      `json:"scientific_accepted"`
	OwnerEligible                   bool      `json:"owner_eligible"`
	DispatchAuthorized              bool      `json:"dispatch_authorized"`
	NewWorkerOrController           bool      `json:"new_worker_or_controller"`
	PaidAPICalls                    int       `json:"paid_api_calls"`
}

func f14Check(v F14Evidence) error {
	if v.Schema != F14Schema || len(v.F8Artifact) < 16 || len(v.F8Artifact) > F8MaxBytes ||
		len(v.F8ArtifactSHA256) != 64 || len(v.F8CheckpointSHA256) != 64 ||
		v.Classification != F14NO_GO || !v.DevelopmentOnly ||
		!v.EarlierNegativeResultsPreserved || v.IndependentFirstUseConsumed ||
		v.ScientificAccepted || v.OwnerEligible || v.DispatchAuthorized ||
		v.NewWorkerOrController || v.PaidAPICalls != 0 ||
		v.F10.Classification != F10ReviewNO_GO || v.F10.G2ThresholdPassingArms != 0 ||
		v.F13.Classification != F13NO_GO || v.F13.PassingArms != 0 ||
		!v.F13.EarlierNegativePreserved {
		return errF14
	}
	cp, err := F8Import(v.F8Artifact, v.F8ArtifactSHA256)
	if err != nil || cp.CheckpointSHA256 != v.F8CheckpointSHA256 ||
		v.F10.ParentF8CheckpointSHA256 != cp.CheckpointSHA256 ||
		F10Validate(v.F10) != nil || F13Validate(v.F13) != nil {
		return errF14
	}
	return nil
}

// F14Export is side-effect free and development-only. It accepts only reports
// generated by the existing native F8/F10/F13 source and emits canonical bytes.
func F14Export(checkpoint F8Checkpoint, benefit F10Review, drift F13Report) ([]byte, string, error) {
	checkpointRaw, checkpointSHA, err := F8Export(checkpoint)
	if err != nil {
		return nil, "", errF14
	}
	v := F14Evidence{
		Schema: F14Schema, F8Artifact: checkpointRaw,
		F8ArtifactSHA256:   checkpointSHA,
		F8CheckpointSHA256: checkpoint.CheckpointSHA256,
		F10:                benefit, F13: drift, Classification: F14NO_GO,
		DevelopmentOnly: true, EarlierNegativeResultsPreserved: true,
	}
	if f14Check(v) != nil {
		return nil, "", errF14
	}
	raw, err := json.Marshal(v)
	if err != nil || len(raw) == 0 || len(raw)+1 > F14MaxBytes {
		return nil, "", errF14
	}
	raw = append(raw, '\n')
	return raw, f3Hash(raw), nil
}

// F14Import requires an independently supplied *whole-bundle* artifact SHA.
// It rejects valid-but-different and forged payloads even if rehashed locally.
// Its output remains non-executing development evidence, never dispatch authority.
func F14Import(raw []byte, expectedArtifactSHA256 string) (F14Evidence, error) {
	if len(raw) < 20 || len(raw) > F14MaxBytes ||
		len(expectedArtifactSHA256) != 64 || f3Hash(raw) != expectedArtifactSHA256 {
		return F14Evidence{}, errF14
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var v F14Evidence
	if decoder.Decode(&v) != nil || decoder.Decode(new(any)) != io.EOF {
		return F14Evidence{}, errF14
	}
	canonical, err := json.Marshal(v)
	if err != nil || !bytes.Equal(raw, append(canonical, '\n')) || f14Check(v) != nil {
		return F14Evidence{}, errF14
	}
	return v, nil
}
