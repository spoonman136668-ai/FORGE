// Eureka F6 converts existing F5 TRAIN-only action-consequence observations
// into bounded alternative Go-source readouts. Source is parsed but NOT built,
// executed, merged, dispatched or installed. A typed mirror measures DEV only.
package nativediscovery

import (
 "encoding/json"
 "errors"
 "fmt"
 "go/parser"
 "go/token"
 "reflect"
)

const F6Schema = "forge.native-discovery.feedback-repair-development.v1"
const F6Families = 4
var errF6 = errors.New("FORGE_EUREKA_F6_FEEDBACK_REPAIR_INVALID")

func f6Families() [F6Families]string {
 return [F6Families]string{"constant","cue-parity","mode-parity","cue-mode-xor"}
}
func f6Pattern(family string, cue,mode int)(int,error){
 if cue<0||cue>=4||mode<0||mode>=2{return 0,errF6}
 flip:=false
 switch family {
 case "constant": flip=false
 case "cue-parity": flip=cue%2==1
 case "mode-parity": flip=mode==1
 case "cue-mode-xor": flip=cue%2!=(mode%2)
 default: return 0,errF6
 }
 if flip{return -1,nil}
 return 1,nil
}
func f6Condition(family string)(string,error){
 switch family {
 case "constant":return "false",nil
 case "cue-parity":return "c.Cue%2==1",nil
 case "mode-parity":return "c.Mode==1",nil
 case "cue-mode-xor":return "c.Cue%2!=(c.Mode%2)",nil
 }
 return "",errF6
}

// The emitted source is a real, parseable self-contained Go type proposal,
// but it is NOT dynamically compiled. The existing f3Core Observe/Load
// interfaces are reused in the proposal and in the typed development mirror.
func f6Source(family string,phase int)(string,error){
 condition,err:=f6Condition(family)
 if err!=nil||phase!=1&&phase!= -1{return "",errF6}
 source:=fmt.Sprintf(`// Code generated by FORGE F6 bounded feedback grammar; NOT activated.
// Source-only candidate, not original-owner or scientific authority.
package nativediscovery
type f6RepairCandidate struct { f3Core }
func (m *f6RepairCandidate) Predict(c f2Context) int {
 if c.Regime<0||c.Regime>1||c.Cue<0||c.Cue>3||c.Mode<0||c.Mode>1{return 1}
 if direct,seen:=f2major(m.Counts[c.Regime][c.Cue][c.Mode]);seen{return direct}
 sign:=%d
 if %s {sign= -sign}
 return sign
}
`,phase,condition)
 if _,err:=parser.ParseFile(token.NewFileSet(),"f6_repair_generated.go",source,parser.AllErrors);err!=nil{
  return "",errF6
 }
 return source,nil
}

type f6Repair struct {
 f3Core
 Family string
 Phase int
}
func(m *f6Repair)Predict(c f2Context)int{
 if c.Regime<0||c.Regime>1||c.Cue<0||c.Cue>3||c.Mode<0||c.Mode>1{return 1}
 if direct,seen:=f2major(m.Counts[c.Regime][c.Cue][c.Mode]);seen{return direct}
 pattern,err:=f6Pattern(m.Family,c.Cue,c.Mode)
 if err!=nil||m.Phase!=1&&m.Phase!= -1{return 1}
 return pattern*m.Phase
}

