// No F5 diagnostic accuracy, test label, world seed or environment evaluator
// is accepted here: candidate generation sees only the six actually observed
// training transitions. The caller must authenticate F5 separately.
func f6Propose(probes []F5Probe)([]F6GeneratedCandidate,error){
 return f6ProposeN(probes,F5ProbeBudget)
}
// f6ProposeN preserves the original six-query behavior and also accepts
// the first three already-observed F5 training events for F7 generation one.
// No partial or non-prefix batches, unknown seeds or new probes are created.
func f6ProposeN(probes []F5Probe,n int)([]F6GeneratedCandidate,error){
 if (n!=3&&n!=F5ProbeBudget)||len(probes)!=n{return nil,errF6}
 used:=[8]bool{}
 for i,p:=range probes{
  key:=p.Cue*2+p.Mode
  if p.Step!=i||p.Cue<0||p.Cue>=4||p.Mode<0||p.Mode>=2||
   key<0||key>=8||used[key]||p.Action!=i%2||
   p.ObservedEffect!=1&&p.ObservedEffect!= -1||
   p.DivergentPairs!=f5Pairs(p.PreObservationPredictions){
   return nil,errF6
  }
  for _,x:=range p.PreObservationPredictions{
   if x!=1&&x!= -1{return nil,errF6}
  }
  used[key]=true
 }
 out:=make([]F6GeneratedCandidate,0,F6Families)
 seenSources:=map[string]bool{}
 for _,family:=range f6Families(){
  correctPositive,correctNegative:=0,0
  for _,p:=range probes{
   pattern,err:=f6Pattern(family,p.Cue,p.Mode)
   if err!=nil{return nil,errF6}
   observed:=p.ObservedEffect
   if p.Action==1{observed= -observed}
   if pattern==observed{correctPositive++}else{correctNegative++}
  }
  phase,correct:=1,correctPositive
  if correctNegative>correctPositive{phase,correct= -1,correctNegative}
  source,err:=f6Source(family,phase)
  if err!=nil{return nil,errF6}
  sha:=f3Hash([]byte(source))
  if len(sha)!=64||seenSources[sha]{return nil,errF6}
  seenSources[sha]=true
  out=append(out,F6GeneratedCandidate{
   Family:family,Phase:phase,TrainingCorrect:correct,
   TrainingTotal:len(probes),SourceSHA256:sha,GeneratedGoSource:source,
  })
 }
 return out,nil
}
func f6FeedbackSHA(arm F5ArmResult,parent F5Report)string{
 raw,_:=json.Marshal(struct{
  ParentSource string
  Seed uint32
  Policy string
  Probes []F5Probe
 }{parent.F4GeneratedSourceSHA256,arm.Seed,arm.Policy,arm.Probes})
 return f3Hash(raw)
}
func f6BuildArm(arm F5ArmResult,parent F5Report)(F6ArmResult,error){
 if !f5ValidSeed(arm.Seed)||arm.TrainObservations!=F2TrainCount||
  arm.ProbeObservations!=F5ProbeBudget||
  arm.ScoredDecisionsPerModel!=F2EvaluationCount||
  parent.F4GeneratedSourceSHA256==""||
  (arm.Policy!="disagreement"&&arm.Policy!="fixed"&&arm.Policy!="random"){
  return F6ArmResult{},errF6
 }
 proposals,err:=f6Propose(arm.Probes)
 if err!=nil||len(proposals)!=F6Families{return F6ArmResult{},errF6}
 out:=F6ArmResult{Seed:arm.Seed,ParentF5Policy:arm.Policy,
  ParentF5SourceSHA256:parent.F4GeneratedSourceSHA256,
  FeedbackSHA256:f6FeedbackSHA(arm,parent),TrainingObservations:F2TrainCount,
  FeedbackObservations:F5ProbeBudget,DevScoredDecisionsPerCandidate:F2EvaluationCount,
  Candidates:make([]F6GeneratedCandidate,0,F6Families),
  PriorF5SelectedDevChangedWorldAccuracyPct:arm.SelectedAccuracyPct,
  StrongestConventionalDevAccuracyPct:arm.StrongestControlAccuracyPct}
 selected:=0
 for i,proposal:=range proposals{
  // A fresh typed mirror of the emitted structural algorithm receives exactly
  // the F5 arm's training and six observed interventions. No test data updates.
  model:=&f6Repair{Family:proposal.Family,Phase:proposal.Phase}
  if err:=f2teach([]f2Observer{model},f2training(arm.Seed));err!=nil{return F6ArmResult{},errF6}
  for _,p:=range arm.Probes{
   transition:=f2Transition{Context:f2Context{Regime:1,Cue:p.Cue,Mode:p.Mode},
    Action:p.Action,Effect:p.ObservedEffect}
   if err:=model.Observe(transition);err!=nil{return F6ArmResult{},errF6}
  }
  success,total:=f2score(model,arm.Seed,1)
  if total!=F2EvaluationCount{return F6ArmResult{},errF6}
  proposal.DevChangedWorldAccuracyPct=f2accuracy(success,total)
  out.Candidates=append(out.Candidates,proposal)
  // Never rank by the F2 dev score: the selection is TRAIN feedback only.
  if proposal.TrainingCorrect>proposals[selected].TrainingCorrect{selected=i}
 }
 chosen:=out.Candidates[selected]
 out.SelectedFamily=chosen.Family
 out.SelectedSourceSHA256=chosen.SourceSHA256
 out.SelectedTrainingCorrect=chosen.TrainingCorrect
 out.SelectedDevChangedWorldAccuracyPct=chosen.DevChangedWorldAccuracyPct
 out.GainOverF5PP=chosen.DevChangedWorldAccuracyPct-arm.SelectedAccuracyPct
 out.GainOverStrongestControlPP=chosen.DevChangedWorldAccuracyPct-arm.StrongestControlAccuracyPct
 if out.GainOverStrongestControlPP<=0{out.DevelopmentClassification="F6_DEV_NO_GO"} else {out.DevelopmentClassification="F6_DEV_DIAGNOSTIC_AHEAD_UNVERIFIED"}
 return out,nil
}

func F6Development()(F6Report,error){
 parent,err:=F5Development()
 if err!=nil||F5ValidatePreview(parent)!=nil||parent.Schema!=F5Schema||
  parent.TrainingSeeds!=f4TrainingSeeds()||parent.Policies!=f5Policies()||
  len(parent.Arms)!=6||parent.IndependentHoldoutConsumed||
  parent.NewMechanismGenerated||parent.ScientificAccepted||
  parent.GeneralRSIProven||parent.OwnerActivation||parent.DispatchAuthorized||
  parent.AgentCalls!=0||parent.PaidAPICalls!=0{
  return F6Report{},errF6
 }
 out:=F6Report{Schema:F6Schema,F5Schema:parent.Schema,
  F5ParentGeneratedSourceSHA256:parent.F4GeneratedSourceSHA256,
  NativeGeneratorFrozenSHA256:parent.NativeGeneratorFrozenSHA256,
  SyntheticTrainingHistorySHA256:parent.SyntheticTrainingHistorySHA256,
  TrainingSeeds:f4TrainingSeeds(),Policies:f5Policies(),Families:f6Families(),
  Arms:make([]F6ArmResult,0,len(parent.Arms)),DevelopmentOnly:true,
  GeneratedGoSourceNotCompiled:true}
 for index,arm:=range parent.Arms{
  if arm.Seed!=out.TrainingSeeds[index/3]||arm.Policy!=out.Policies[index%3]{
   return F6Report{},errF6
  }
  row,err:=f6BuildArm(arm,parent)
  if err!=nil{return F6Report{},err}
  out.Arms=append(out.Arms,row)
  out.TotalGeneratedSourcePrograms+=len(row.Candidates)
 }
 if out.TotalGeneratedSourcePrograms!=6*F6Families{return F6Report{},errF6}
 return out,nil
}
func F6ValidatePreview(report F6Report)error{
 exact,err:=F6Development()
 if err!=nil||!reflect.DeepEqual(report,exact){return errF6}
 return nil
}
