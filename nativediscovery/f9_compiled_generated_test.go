const f9FixedSourceHeader = "// Code generated from FORGE F6's fixed grammar for F9 DEV qualification.\n// Bounded, checked-in, compiled as part of original Go regression; NOT activated.\npackage nativediscovery\n"
const f9OriginalSourceHeader = "// Code generated by FORGE F6 bounded feedback grammar; NOT activated.\n// Source-only candidate, not original-owner or scientific authority.\npackage nativediscovery\n"

type f9Fixture struct{
 family string
 phase int
 compiledType string
 constructor func() f3Executable
}
func f9Fixtures() []f9Fixture{
 return []f9Fixture{
  {"constant",1,"f9CompiledConstantPositive",func() f3Executable{return &f9CompiledConstantPositive{}}},
  {"constant",-1,"f9CompiledConstantNegative",func() f3Executable{return &f9CompiledConstantNegative{}}},
  {"cue-parity",1,"f9CompiledCueParityPositive",func() f3Executable{return &f9CompiledCueParityPositive{}}},
  {"cue-parity",-1,"f9CompiledCueParityNegative",func() f3Executable{return &f9CompiledCueParityNegative{}}},
  {"mode-parity",1,"f9CompiledModeParityPositive",func() f3Executable{return &f9CompiledModeParityPositive{}}},
  {"mode-parity",-1,"f9CompiledModeParityNegative",func() f3Executable{return &f9CompiledModeParityNegative{}}},
  {"cue-mode-xor",1,"f9CompiledCueModeXorPositive",func() f3Executable{return &f9CompiledCueModeXorPositive{}}},
  {"cue-mode-xor",-1,"f9CompiledCueModeXorNegative",func() f3Executable{return &f9CompiledCueModeXorNegative{}}},
 }
}

// Every byte in the real compiled generated source must be explained by the
// original F6 source generator. The ONLY transformation renames the type so
// eight variants can coexist in the existing Go package and regression.
func TestF9CompiledSourceExactlyMatchesFrozenF6Generation(t *testing.T){
 fixtures:=f9Fixtures()
 if len(fixtures)!=8{t.Fatal("missing bounded generated source fixture")}
 expected:=f9FixedSourceHeader
 seen:=map[string]bool{}
 for _,row:=range fixtures{
  canonical,err:=f6Source(row.family,row.phase)
  if err!=nil||!strings.HasPrefix(canonical,f9OriginalSourceHeader){
   t.Fatal("frozen F6 grammar changed or is not canonical")
  }
  key:=row.family+":"+row.compiledType
  if seen[key]{t.Fatal("duplicate generated program type")}
  seen[key]=true
  body:=strings.TrimPrefix(canonical,f9OriginalSourceHeader)
  if strings.Count(body,"f6RepairCandidate")!=2{
   t.Fatal("bounded source has unexpected type occurrences")
  }
  expected+=strings.ReplaceAll(body,"f6RepairCandidate",row.compiledType)
  if row.constructor()==nil{t.Fatal("generated implementation was not compiled")}
 }
 raw,err:=os.ReadFile("f9_compiled_generated.go")
 if err!=nil||!bytes.Equal(raw,[]byte(expected)){
  t.Fatal("actual compiled Go source diverged from frozen F6 generator bytes")
 }
 bad:=append([]byte(nil),raw...)
 bad=bytes.Replace(bad,[]byte("sign:=1"),[]byte("sign:= -1"),1)
 if bytes.Equal(bad,[]byte(expected)){t.Fatal("mutated source wrongly accepted")}
 t.Log("F9_COMPILER_SOURCE_PROVENANCE=PASS; eight fixed F6 grammar programs compiled in native Go package")
}

// These are actual compiled programs, not a typed mirror or a parser/typecheck.
// Only the checked-in reviewed F6 grammar can enter the binary; no subprocess.
func TestF9EightCompiledProgramsExecuteAndRestoreActualF8Learning(t *testing.T){
 checkpoint,err:=F8Development()
 if err!=nil||F8Validate(checkpoint)!=nil{t.Fatal("F8 history not qualified",err)}
 fixtures:=f9Fixtures()
 restored:=0
 selected:=0
 for _,arm:=range checkpoint.Arms{
  for _,step:=range arm.Steps{
   if step.Generation<1||step.Generation>2||step.SnapshotSHA256!=f3Hash(step.SnapshotBytes){
    t.Fatal("invalid learning snapshot identity")
   }
   chosenFound:=false
   for _,spec:=range fixtures{
    actual:=spec.constructor()
    if err:=actual.Load(step.SnapshotBytes);err!=nil{t.Fatal("compiled source cold load failed",err)}
    mirror:=&f6Repair{Family:spec.family,Phase:spec.phase}
    if err:=mirror.Load(step.SnapshotBytes);err!=nil{t.Fatal("F6 typed mirror cold load failed",err)}
    actualBytes,err:=actual.Snapshot()
    if err!=nil||!bytes.Equal(actualBytes,step.SnapshotBytes){
     t.Fatal("compiled candidate did not preserve exact learned-state bytes")
    }
    for regime:=0;regime<2;regime++{for cue:=0;cue<4;cue++{for mode:=0;mode<2;mode++{
     ctx:=f2Context{Regime:regime,Cue:cue,Mode:mode}
     got,want:=actual.Predict(ctx),mirror.Predict(ctx)
     if got!=want||got!=1&&got!= -1{
      t.Fatalf("compiled generated source parity FAIL seed=%d policy=%s gen=%d family=%s phase=%d ctx=%+v got=%d want=%d",
       arm.Seed,arm.Policy,step.Generation,spec.family,spec.phase,ctx,got,want)
     }
    }}}
    // A separately instantiated compiled fixture must also obey the
    // generated fallback in every *unobserved* context before training.
    virgin:=spec.constructor()
    for cue:=0;cue<4;cue++{for mode:=0;mode<2;mode++{
     pattern,e:=f6Pattern(spec.family,cue,mode)
     if e!=nil||virgin.Predict(f2Context{Regime:1,Cue:cue,Mode:mode})!=pattern*spec.phase{
      t.Fatal("compiled generated code did not implement the causal grammar")
     }
    }}
    if step.SelectedFamily==spec.family&&step.SelectedPhase==spec.phase{
     chosenFound=true
     selected++
     if f8Predictions(mirror)!=step.PredictionSHA256{
      t.Fatal("F8 selected mechanism learned-state predictions not retained")
     }
    }
    restored++
   }
   if !chosenFound{t.Fatal("no compiled F6 source matches selected F8 mechanism")}
  }
 }
 if restored!=6*2*8||selected!=6*2{
  t.Fatalf("compiled F9 covers insufficient history snapshots %d, selected %d",restored,selected)
 }
 t.Logf("F9_ACTUAL_GENERATED_SOURCE_EXECUTION=PASS variants=%d restored_state_checks=%d selected_checkpoints=%d; no_worker_dispatch=true no_new_subprocess=true",len(fixtures),restored,selected)
}
