def classify_model_free_failure(exc: Exception) -> str:
    """Never surface unreviewed exception messages or implicit authority.

    An OSError may contain a sensitive filesystem path, so classify its type
    before even examining the message. No string other than a source-review-
    allowlisted literal can escape this function.
    """
    if isinstance(exc, OSError):
        return "OS_ERROR_NO_DETAILS"
    code = str(exc)
    if code in SAFE_CODES:
        return code
    if type(exc).__name__ == "F139Error":
        return "UNCLASSIFIED_F139_ERROR"
    if isinstance(exc, ValueError):
        return "UNCLASSIFIED_VALUE_ERROR"
    return "UNCLASSIFIED_FAILURE"
