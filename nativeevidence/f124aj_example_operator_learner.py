"""F124-AJ example-conditioned operator learner; no hand-coded causal rules.

Learn a bijective input-bit to output-bit correspondence and per-output
complement flag from PUBLIC paired demonstrations in each graph. Learn the
number of demonstrations from new TRAIN labels; once frozen, infer maps for
unseen HOLDOUT tasks from unlabeled support only. No operator-name parser,
family-specific branch, source oracle, protected data or evaluator import.

Inductive bias is explicit: ONLY bit-permutations plus XOR complements.
This is few-shot supervised relation induction, not a neural learner.
"""
from __future__ import annotations
import math,re
from collections import Counter
import f124ag_transition_models as ag
import f124ae_scoring_transfer as old
import f124q_fresh_source as q

TAG=re.compile(r"^rel_task_([a-f0-9]{12}):(.+)$")
COUNTS=(8,12,16,24)
ETA=.1

def need(ok,name):q.need(ok,"F124AJ_LEARNER_"+name)

def public_task(graph):
    need(type(graph) is dict and
         set(graph)=={"start","target","roles","edges","demos"},
         "SOURCE_ONLY_PUBLIC_INPUT")
    roles=graph["roles"]
    need(type(roles) is list and 7<=len(roles)<=15,
         "PUBLIC_BOUNDED_ROLE_DEPTH")
    match=[TAG.fullmatch(role) for role in roles]
    need(all(x is not None for x in match),"OPAQUE_TASK_ROLE_GRAMMAR")
    task=match[0].group(1)
    need(all(x.group(1)==task for x in match),"TASK_ID_UNIFORM")
    result={"start":graph["start"],"target":graph["target"],
            "roles":[x.group(2) for x in match],"edges":[]}
    for e in graph["edges"]:
        m=TAG.fullmatch(e["role"])
        need(m is not None and m.group(1)==task,
             "PUBLIC_EDGE_TASK_CONSISTENCY")
        result["edges"].append({"from":e["from"],"to":e["to"],
                                "role":m.group(2),
                                "src_bits":list(e["src_bits"]),
                                "dst_bits":list(e["dst_bits"])})
    demos=graph["demos"]
    need(type(demos) is list and len(demos)==24,"PUBLIC_24_SUPPORT_PAIRS")
    for item in demos:
        need(type(item) is dict and
             set(item)=={"input_bits","output_bits"} and
             all(type(item[key]) is list and len(item[key])==16
                 and all(type(bit) is int and bit in (0,1)
                         for bit in item[key])
                 for key in ("input_bits","output_bits")),
             "SUPPORT_PAIR_VALIDITY")
    return result,demos,task

def learn_mapping(demos,amount):
    """Per-output bit-coordinate exact consistency from demonstration pairs.

    Outputs are generated by an unknown permutation plus complement, but
    this function NEVER consumes the true permutation, semantic label, or
    operator name. Ambiguity becomes a recorded failure, not oracle fallback.
    """
    need(amount in COUNTS and len(demos)==24,"FROZEN_TRAIN_AMOUNT")
    selected=demos[:amount]
    pairs=[]
    ambiguous=0
    comparisons=0
    for output_coord in range(16):
        choices=[]
        for input_coord in range(16):
            for flip in (0,1):
                comparisons+=amount
                if all(x["output_bits"][output_coord]==
                       (x["input_bits"][input_coord]^flip)
                       for x in selected):
                    choices.append((input_coord,flip))
        if len(choices)!=1:
            ambiguous+=1
        pairs.append(choices[0] if len(choices)==1 else None)
    mapping_valid=all(v is not None for v in pairs) and len(
                  {v[0] for v in pairs})==16
    return tuple(pairs) if mapping_valid else None,{
        "pairs_used":amount,"constraints_considered":16*16*2*amount,
        "comparisons_declared":comparisons,
        "ambiguous_output_coordinates":ambiguous,
        "unique_bijective_mapping":mapping_valid,
        "frozen_inductive_bias":"permutation_xor",
        "semantic_operator_names_consumed":False}

def normalize(graph,amount):
    base,demos,task=public_task(graph)
    mapping,learn=learn_mapping(demos,amount)
    if mapping is None:
        return None,{"learning":learn,
                     "task_nonce":task,"edge_bit_operations":0,
                     "additional_retained_states":0}
    operations=0
    for e in base["edges"]:
        old_src=e["src_bits"]
        raw=[0]*16
        for out_coord,(input_coord,flip) in enumerate(mapping):
            raw[input_coord]=old_src[out_coord]^flip
            operations+=1
        e["src_bits"]=raw
    ag.frozen.prior.parent.validate_15(base)
    return base,{"learning":learn,"task_nonce":task,
                 "edge_bit_operations":operations,
                 "additional_retained_states":0}

def ygg(graph,base,delta,amount):
    normalized,observer=normalize(graph,amount)
    if normalized is None:return -1.e9,None,observer
    score,raw,ratio,work=ag.ygg_transition(
        normalized,list(base),list(delta),ETA)
    need(work["max_active"]<=7 and work["max_retained"]<=9,
         "ORIGINAL_7_PLUS_9")
    return score,work,observer

def wing(graph,base,delta,amount,three=False):
    normalized,observer=normalize(graph,amount)
    if normalized is None:return -1.e9,None,observer
    score,work=(old.frozen_three(normalized,list(base),list(delta))
                if three else old.frozen_packed(
                    normalized,list(base),list(delta)))
    if not three:
        need(work["max_active"]<=64 and
             work["max_states_per_node"]==1 and
             work["max_packed_bits_per_state"]==12,
             "NO_CAPACITY_INCREASE")
    return score,work,observer

def old_ygg(graph,base,delta):
    # Source-blind old model only needs original standard graph shape with
    # opaque roles left in place; no demo keys in original validator.
    result={k:graph[k] for k in ("start","target","roles","edges")}
    score,raw,ratio,work=ag.ygg_transition(
        result,list(base),list(delta),ETA)
    return score,work

def old_wing(graph,base,delta,three=False):
    result={k:graph[k] for k in ("start","target","roles","edges")}
    return (old.frozen_three(result,list(base),list(delta))
            if three else old.frozen_packed(result,list(base),list(delta)))

def fit_demo_count(cases,base,delta):
    need(len(cases)==48,"TRAIN_ONLY_COMPLETE_COHORT")
    results=[]
    for amount in COUNTS:
        paired=0;failures=0
        for seed,vector,family,operator,nonce,p,n in cases:
            a,_,diag1=ygg(p,base,delta,amount)
            b,_,diag2=ygg(n,base,delta,amount)
            paired+=int(a>=0 and b<0)
            failures+=int(not diag1["learning"]["unique_bijective_mapping"])
            failures+=int(not diag2["learning"]["unique_bijective_mapping"])
        results.append({"demos":amount,"paired":paired,
                        "ambiguous_graphs":failures})
    selected=sorted(results,key=lambda x:(-x["paired"],x["demos"]))[0]
    return selected,results
